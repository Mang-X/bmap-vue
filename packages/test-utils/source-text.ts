/**
 * **文本门禁**的共享工具（`#104` 第三批收口）
 *
 * 仓库里有多条门禁是「读源码 / 读产物，断言某个标识符**不存在**」（`check:no-bmapgl`、
 * 默认 loader 边界、能力目录、`./core` 公开面复核……）。它们有一个共同的**假失败**来源：
 * 注释里正当地写着「旧默认值是 X，现在不是了」这类说明 —— 判定对象会从实现变成文案，
 * 为了消误报去改注释是本末倒置。所以这类判定都要**先剥注释**。
 *
 * 剥注释的实现此前在本仓有 **5 份逐字相同的副本**（4 份在 `tests/behavior/*.test.ts` 里各写一遍，
 * 第 5 份出现在 `v3-core-surface.test.ts` 的评审自审）。同一件事写 5 份的代价不是体积，而是
 * **修一处漏洞只改一份**：例如下面「已知限制」里那条 `]//` 形态就是在任何一份里都没被覆盖。
 *
 * ## 已知限制（显式接受，要修就在**这里**修）
 *
 * 行注释的判定要求 `//` 前面是行首、空白或 `;(){}` 之一。因此 `foo[0]// 说明` 这种
 * **紧跟在 `]` 之后**的注释不会被剥掉。历史副本的判定式与本文件**逐字一致** —— 迁移时
 * 刻意没有顺手收紧（那会同时改变另外 4 条既有门禁的语义，不属于本次收口的范围）。
 * 真需要修时，改这一处即可，5 个调用点一起生效。
 */
export function stripComments(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[\s;(){}])\/\/[^\n]*/g, '$1')
}
